import { a, defineData, type ClientSchema } from "@aws-amplify/backend"
import { bidActions } from "../functions/bid-actions/resource"

// The terms of a proposal, stored on every BidVersion. startDate and paymentTerms are
// optional here only because bids placed before proposals existed don't have them.
const proposalTerms = {
  amount: a.float().required(),
  scope: a.string().required(),
  estimatedDays: a.integer().required(),
  startDate: a.date(),
  paymentTerms: a.string(),
  materialsCost: a.float(),
  laborCost: a.float(),
  materialsDetail: a.string(),
  included: a.string().array(),
  excluded: a.string().array(),
  notes: a.string(),
}

// New proposals (placeBid / reviseBid) and confirmed Agreements must have every required term.
const proposalArguments = {
  ...proposalTerms,
  startDate: a.date().required(),
  paymentTerms: a.string().required(),
}

/**
 * WorkBid database schema (DynamoDB tables + API, generated by Amplify).
 * Mirrors lib/types.ts. Every user is identified by their Cognito user id ("sub"),
 * so clientId / contractorId / senderId fields all hold a sub.
 *
 * Categories stay in the frontend (lib/mock-data.ts) since they never change.
 * Contractor rating / review count / completed projects are calculated from
 * Review and Project rows instead of stored, so they can't get out of sync.
 */
// Field rule for project fields only the bid-actions function may change: the owner
// can set them when creating the project, and everyone can read them.
const serverManaged = (allow: Parameters<Parameters<ReturnType<typeof a.string>["authorization"]>[0]>[0]) => [
  allow.ownerDefinedIn("clientId").identityClaim("sub").to(["create", "read"]),
  allow.authenticated().to(["read"]),
  allow.guest().to(["read"]),
]

const schema = a
  .schema({
  UserType: a.enum(["client", "contractor"]),
  // "awarded" is shown as "Hired": a contractor's agreement was confirmed.
  ProjectStatus: a.enum(["open", "awarded", "in_progress", "completed"]),
  // "pending" is shown as "Submitted". "closed" = another contractor was hired.
  BidStatus: a.enum(["pending", "revision_requested", "accepted", "rejected", "withdrawn", "closed"]),
  BidVersionStatus: a.enum(["active", "superseded", "accepted"]),
  ChangeOrderStatus: a.enum(["proposed", "approved", "declined"]),

  // One per signed-up user. userId = Cognito sub.
  // Email is not stored here: every signed-in user can read profiles, and Cognito
  // already keeps each user's email private (read it with fetchUserAttributes()).
  UserProfile: a
    .model({
      userId: a.id().required(),
      firstName: a.string().required(),
      lastName: a.string().required(),
      userType: a.ref("UserType").required(),
      avatar: a.string(),
    })
    .identifier(["userId"])
    .authorization((allow) => [
      allow.ownerDefinedIn("userId").identityClaim("sub"),
      allow.authenticated().to(["read"]),
    ]),

  // Extra details for contractor accounts. contractorId = Cognito sub.
  ContractorProfile: a
    .model({
      contractorId: a.id().required(),
      businessName: a.string().required(),
      contractorName: a.string().required(),
      licenseNumber: a.string(),
      yearsExperience: a.integer(),
      location: a.string(),
      specialty: a.string(),
      // No "verified" field yet: the owner can edit every field here, so they could
      // verify themselves. Add it back later behind an admin-only rule.
      avatar: a.string(),
      about: a.string(),
      skills: a.string().array(),
      services: a.string().array(),
    })
    .identifier(["contractorId"])
    .authorization((allow) => [
      allow.ownerDefinedIn("contractorId").identityClaim("sub"),
      allow.authenticated().to(["read"]),
      allow.guest().to(["read"]),
    ]),

  Project: a
    .model({
      clientId: a.id().required(),
      clientName: a.string().required(),
      categoryId: a.string().required(),
      title: a.string().required(),
      description: a.string().required(),
      location: a.string().required(),
      budgetMin: a.float().required(),
      budgetMax: a.float().required(),
      // e.g. "Within 2 weeks" or "Flexible"
      timeline: a.string(),
      // Hiring fields: set on create, then changed only by the bid-actions function
      // (confirmAgreement / completeProject), so a client can't mark a project hired
      // without a confirmed agreement.
      status: a.ref("ProjectStatus").required().authorization(serverManaged),
      startDate: a.datetime().authorization(serverManaged),
      completionDate: a.datetime().authorization(serverManaged),
      awardedContractorId: a.id().authorization(serverManaged),
      images: a.string().array(),
      bids: a.hasMany("Bid", "projectId"),
    })
    .secondaryIndexes((index) => [index("clientId"), index("status")])
    .authorization((allow) => [
      allow.ownerDefinedIn("clientId").identityClaim("sub"),
      allow.authenticated().to(["read"]),
      allow.guest().to(["read"]),
    ]),

  // One per contractor per project. Its amount/estimatedDays/proposalMessage mirror the
  // current BidVersion, so lists can show the latest offer without loading versions.
  Bid: a
    .model({
      projectId: a.id().required(),
      project: a.belongsTo("Project", "projectId"),
      contractorId: a.id().required(),
      // Copied from the project so the client can read the bid.
      clientId: a.id().required(),
      amount: a.float().required(),
      estimatedDays: a.integer().required(),
      // The current version's scope of work.
      proposalMessage: a.string().required(),
      status: a.ref("BidStatus").required(),
      // When the contractor last revised the bid.
      amountUpdatedAt: a.datetime(),
      currentVersionId: a.id(),
      currentVersion: a.integer(),
      // The amount before the latest revision, to show what changed.
      previousAmount: a.float(),
      // The client's note when they ask for a revision.
      revisionNote: a.string(),
      revisionRequestedAt: a.datetime(),
    })
    .secondaryIndexes((index) => [index("projectId"), index("contractorId")])
    // Read-only from the browser: every change goes through the mutations below,
    // which check the rules on the server.
    .authorization((allow) => [
      allow.ownerDefinedIn("contractorId").identityClaim("sub").to(["read"]),
      allow.ownerDefinedIn("clientId").identityClaim("sub").to(["read"]),
    ]),

  // One offer from a contractor. A revision adds a new version and marks the old one
  // superseded; versions are never edited, so the full negotiation history is kept.
  BidVersion: a
    .model({
      bidId: a.id().required(),
      projectId: a.id().required(),
      contractorId: a.id().required(),
      clientId: a.id().required(),
      version: a.integer().required(),
      status: a.ref("BidVersionStatus").required(),
      // What the contractor says changed from the previous version.
      changeSummary: a.string(),
      ...proposalTerms,
    })
    .secondaryIndexes((index) => [index("bidId").sortKeys(["version"])])
    .authorization((allow) => [
      allow.ownerDefinedIn("contractorId").identityClaim("sub").to(["read"]),
      allow.ownerDefinedIn("clientId").identityClaim("sub").to(["read"]),
    ]),

  // The confirmed deal: a snapshot of the exact accepted version. Created only by
  // confirmAgreement and never updated; later changes are ChangeOrders.
  Agreement: a
    .model({
      projectId: a.id().required(),
      projectTitle: a.string().required(),
      bidId: a.id().required(),
      bidVersionId: a.id().required(),
      version: a.integer().required(),
      clientId: a.id().required(),
      clientName: a.string().required(),
      contractorId: a.id().required(),
      contractorName: a.string().required(),
      businessName: a.string(),
      confirmedAt: a.datetime().required(),
      ...proposalArguments,
    })
    .secondaryIndexes((index) => [index("projectId"), index("bidId")])
    .authorization((allow) => [
      allow.ownerDefinedIn("contractorId").identityClaim("sub").to(["read"]),
      allow.ownerDefinedIn("clientId").identityClaim("sub").to(["read"]),
    ]),

  // A change to a confirmed agreement, proposed by one side and approved by the other.
  ChangeOrder: a
    .model({
      agreementId: a.id().required(),
      projectId: a.id().required(),
      clientId: a.id().required(),
      contractorId: a.id().required(),
      proposedBy: a.id().required(),
      description: a.string().required(),
      // Added to (or, if negative, taken off) the agreed price / timeline.
      amountChange: a.float().required(),
      daysChange: a.integer().required(),
      status: a.ref("ChangeOrderStatus").required(),
      respondedAt: a.datetime(),
    })
    .secondaryIndexes((index) => [index("projectId")])
    .authorization((allow) => [
      allow.ownerDefinedIn("contractorId").identityClaim("sub").to(["read"]),
      allow.ownerDefinedIn("clientId").identityClaim("sub").to(["read"]),
    ]),

  // An in-app notification. Created by the bid-actions function; the user can only
  // read theirs, mark them read, or delete them.
  Notification: a
    .model({
      userId: a.id().required(),
      title: a.string().required(),
      body: a.string().required(),
      href: a.string(),
      read: a.boolean().required(),
    })
    .secondaryIndexes((index) => [index("userId")])
    .authorization((allow) => [allow.ownerDefinedIn("userId").identityClaim("sub").to(["read", "update", "delete"])]),

  // Contractor submits a bid (version 1). The function sets contractorId/clientId/status itself.
  placeBid: a
    .mutation()
    .arguments({ projectId: a.id().required(), ...proposalArguments })
    .returns(a.ref("Bid"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Contractor submits a new version of their bid. expectedVersion is the version they
  // edited; it fails if the bid changed since. (Not "updateBid": the Bid model has one.)
  reviseBid: a
    .mutation()
    .arguments({
      bidId: a.id().required(),
      expectedVersion: a.integer().required(),
      changeSummary: a.string(),
      ...proposalArguments,
    })
    .returns(a.ref("Bid"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Client asks the contractor to revise their bid.
  requestRevision: a
    .mutation()
    .arguments({ bidId: a.id().required(), note: a.string().required() })
    .returns(a.ref("Bid"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Client declines a bid (other bids are unaffected).
  declineBid: a
    .mutation()
    .arguments({ bidId: a.id().required() })
    .returns(a.ref("Bid"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Contractor withdraws their own unaccepted bid.
  withdrawBid: a
    .mutation()
    .arguments({ bidId: a.id().required() })
    .returns(a.ref("Bid"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Client confirms the final terms of a bid's current version: records the Agreement,
  // hires the contractor, and closes every other bid. bidVersionId is the version the
  // client reviewed; it fails if the contractor has revised since.
  confirmAgreement: a
    .mutation()
    .arguments({ bidId: a.id().required(), bidVersionId: a.id().required() })
    .returns(a.ref("Agreement"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Client marks a hired project complete.
  completeProject: a
    .mutation()
    .arguments({ projectId: a.id().required() })
    .returns(a.ref("Project"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Either party proposes a change to a confirmed agreement.
  proposeChangeOrder: a
    .mutation()
    .arguments({
      agreementId: a.id().required(),
      description: a.string().required(),
      amountChange: a.float().required(),
      daysChange: a.integer().required(),
    })
    .returns(a.ref("ChangeOrder"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // The other party approves or declines a proposed change order.
  respondToChangeOrder: a
    .mutation()
    .arguments({ changeOrderId: a.id().required(), approve: a.boolean().required() })
    .returns(a.ref("ChangeOrder"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  Review: a
    .model({
      projectId: a.id().required(),
      projectTitle: a.string().required(),
      clientId: a.id().required(),
      clientName: a.string().required(),
      contractorId: a.id().required(),
      rating: a.integer().required(),
      reviewText: a.string().required(),
    })
    .secondaryIndexes((index) => [index("contractorId"), index("projectId")])
    .authorization((allow) => [
      allow.ownerDefinedIn("clientId").identityClaim("sub"),
      allow.authenticated().to(["read"]),
      allow.guest().to(["read"]),
    ]),

  // A chat thread between one client and one contractor about a project.
  // Created only through the startConversation mutation, which checks the two people
  // are really connected by a bid and fills in their names on the server.
  Conversation: a
    .model({
      projectId: a.id().required(),
      projectTitle: a.string().required(),
      clientId: a.id().required(),
      clientName: a.string().required(),
      contractorId: a.id().required(),
      contractorName: a.string().required(),
      contractorAvatar: a.string(),
    })
    .secondaryIndexes((index) => [index("clientId"), index("contractorId")])
    .authorization((allow) => [
      allow.ownerDefinedIn("clientId").identityClaim("sub").to(["read"]),
      allow.ownerDefinedIn("contractorId").identityClaim("sub").to(["read"]),
    ]),

  // Opens (or returns the existing) conversation between a project's client and a
  // contractor who bid on it. Either of the two can call it.
  startConversation: a
    .mutation()
    .arguments({
      projectId: a.id().required(),
      contractorId: a.id().required(),
    })
    .returns(a.ref("Conversation"))
    .authorization((allow) => [allow.authenticated()])
    .handler(a.handler.function(bidActions)),

  // Written directly by the browser: the sender must be the signed-in user. The app
  // also ignores any message whose sender/receiver aren't the conversation's two people.
  Message: a
    .model({
      conversationId: a.id().required(),
      senderId: a.id().required(),
      senderName: a.string().required(),
      receiverId: a.id().required(),
      messageBody: a.string().required(),
      sentAt: a.datetime().required(),
    })
    .secondaryIndexes((index) => [index("conversationId").sortKeys(["sentAt"])])
    .authorization((allow) => [
      allow.ownerDefinedIn("senderId").identityClaim("sub").to(["create", "read"]),
      allow.ownerDefinedIn("receiverId").identityClaim("sub").to(["read"]),
    ]),
  })
  // Lets the bid-actions function read and write every table.
  .authorization((allow) => [allow.resource(bidActions)])

export type Schema = ClientSchema<typeof schema>

export const data = defineData({
  schema,
  authorizationModes: {
    defaultAuthorizationMode: "userPool",
  },
})
